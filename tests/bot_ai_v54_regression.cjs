'use strict';
const fs=require('node:fs');
const html=fs.readFileSync(require('node:path').join(__dirname,'..','index.html'),'utf8');
const a=html.indexOf('      const BOT_BEHAVIOR_PRIORITY='),b=html.indexOf('      function updateBots(dt)',a);
if(a<0||b<a)throw Error('Missing controller');
const api=new Function(html.slice(a,b)+'\nreturn {select:selectBotBehaviorPlan,local:resolveBotLocalMovement};')();
let n=0;
const ok=(v,s)=>{if(!v)throw Error('V54 FAIL: '+s);n++};
const pos={x:5,y:0,z:7},bot={legYaw:0,pos,unstuckTimer:1,passageStepTimer:1,stuckTimer:1};
const mk=(kind,extra={})=>({kind,target:pos,speed:4,crouch:.3,yaw:.7,...extra});
let p=api.select(bot,[mk('ADVANCE'),mk('MISSION'),mk('ENGAGE',{lookOwner:'VISIBLE_TARGET'})],10);
ok(p.kind==='ENGAGE'&&p.lookOwner==='VISIBLE_TARGET','Contact beats patrol and mission');
ok(!p.route,'Combat cannot inherit route recovery');
ok(bot.unstuckTimer===0&&bot.passageStepTimer===0&&bot.stuckTimer===0,'Entry clears stale movement');
ok(api.local(p,{target:pos,speed:9})===p,'Recovery cannot override combat');
const prior=bot.behavior;
p=api.select(bot,[mk('ENGAGE')],10.1);
ok(bot.behavior===prior&&bot.behavior.enteredAt===10&&bot.behavior.transitions===1,'Same behavior retains entry');
p=api.select(bot,[mk('ENGAGE'),mk('FLANK'),mk('COVER'),mk('RETREAT')],11);
ok(p.kind==='RETREAT'&&p.route,'Retreat wins');
ok(bot.behavior.transitions===2&&bot.behavior.enteredAt===11,'Transition counted once');
p=api.select(bot,[mk('MISSION'),mk('CONTACT_HOLD',{target:null,speed:0,lookOwner:'LAST_CONTACT'})],12);
ok(p.kind==='CONTACT_HOLD'&&!p.route&&p.speed===0,'Recent contact holds before mission');
ok(api.local(p,{target:pos,speed:5})===p,'Hold rejects stale recovery');
p=api.select(bot,[mk('ADVANCE'),mk('SUPPORT'),mk('INVESTIGATE'),mk('MISSION')],13);
ok(p.kind==='MISSION'&&p.route,'Quiet mission owns route');
const detour={x:9,y:0,z:9},local=api.local(p,{target:detour,speed:3,kind:'SIDESTEP'});
ok(local.target===detour&&local.kind===p.kind&&local.yaw===p.yaw&&local.lookOwner===p.lookOwner&&local.crouch===p.crouch,'Detour changes movement only');
ok(api.local(p,{yield:true}).speed===0&&api.local(p,{yield:true}).target===null,'Yield stops movement');
ok(api.local(p,{target:{x:NaN,y:0,z:0},speed:4})===p,'Invalid destination rejected');
p=api.select(bot,[mk('MISSION',{target:null,speed:4})],14);
ok(p.speed===0&&!p.route,'Stationary objective is protected');
p=api.select(bot,[mk('COVER',{route:false,speed:2.1})],15);
ok(!p.route&&p.speed===2.1,'Peek can move without route override');
p=api.select(bot,[mk('HOLD'),mk('DRONE',{target:null,speed:0})],16);
ok(p.kind==='DRONE'&&!p.route,'Drone protects stationary operator');
p=api.select(bot,[mk('INVALID')],17);
ok(p.kind==='HOLD'&&p.speed===0,'Unknown state fails closed');
p=api.select(bot,[mk('ADVANCE',{target:{x:Infinity,y:0,z:0},speed:9,yaw:NaN,crouch:5})],18);
ok(p.target===null&&p.speed===0&&p.crouch===1&&p.yaw===bot.legYaw,'Sanitize invalid proposal');
ok(html.includes('const selectedPlan=selectBotBehaviorPlan(bot,proposals,nowSec);')&&html.includes('moveTargetPos=selectedPlan.target;moveSpeed=selectedPlan.speed;'),'Live integration');
ok(html.includes("if(selectedPlan.kind!=='MISSION')foMissionOrder=null;"),'Losing mission loses route');
ok(html.includes('selectedPlan.route && !bot.passageStepTarget && !bot.unstuckTarget'),'Single local owner');
ok(html.includes('behaviorTransitions:b.behavior?.transitions||0'),'QA transition telemetry');
ok(html.includes('aimSettleSec: 0.34'),'Medium aim preserved');
console.log('BOT AI V54 PASS ('+n+' checks)');
